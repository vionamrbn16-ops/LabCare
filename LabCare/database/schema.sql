-- 1. Tabel profil pengguna
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabel tiket laporan
CREATE TABLE IF NOT EXISTS public.tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    reporter_name TEXT NOT NULL,
    reporter_type TEXT NOT NULL
        CHECK (reporter_type IN ('Siswa', 'Guru')),
    category TEXT NOT NULL
        CHECK (category IN (
            'Hardware',
            'Software',
            'Jaringan',
            'Peralatan',
            'Lainnya'
        )),
    priority TEXT NOT NULL DEFAULT 'Sedang'
        CHECK (priority IN ('Rendah', 'Sedang', 'Tinggi')),
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Done')),
    admin_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tickets ENABLE ROW LEVEL SECURITY;

-- 4. Hak akses tabel profil
GRANT SELECT ON public.profiles TO authenticated;

-- Pengguna hanya dapat membaca profil miliknya
CREATE POLICY "Users can view own profile"
ON public.profiles
FOR SELECT
TO authenticated
USING ((SELECT auth.uid()) = id);

-- 5. Hak akses tabel tiket
GRANT SELECT, INSERT, UPDATE ON public.tickets TO authenticated;

-- Pengguna hanya dapat melihat tiket miliknya
CREATE POLICY "Users can view own tickets"
ON public.tickets
FOR SELECT
TO authenticated
USING ((SELECT auth.uid()) = user_id);

-- Pengguna hanya dapat membuat tiket atas namanya
CREATE POLICY "Users can insert own tickets"
ON public.tickets
FOR INSERT
TO authenticated
WITH CHECK ((SELECT auth.uid()) = user_id);

-- 6. Fungsi untuk memeriksa admin
CREATE SCHEMA IF NOT EXISTS private;

CREATE OR REPLACE FUNCTION private.is_labcare_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = (SELECT auth.uid())
          AND role = 'admin'
    );
$$;

REVOKE ALL ON FUNCTION private.is_labcare_admin()
FROM PUBLIC, anon;

GRANT USAGE ON SCHEMA private TO authenticated;

GRANT EXECUTE ON FUNCTION private.is_labcare_admin()
TO authenticated;

-- 7. Admin dapat melihat seluruh tiket
CREATE POLICY "Admins can view all tickets"
ON public.tickets
FOR SELECT
TO authenticated
USING ((SELECT private.is_labcare_admin()));

-- 8. Admin dapat memperbarui status dan catatan tiket
CREATE POLICY "Admins can update tickets"
ON public.tickets
FOR UPDATE
TO authenticated
USING ((SELECT private.is_labcare_admin()))
WITH CHECK ((SELECT private.is_labcare_admin()));

-- 9. Berikan izin sequence untuk pembuatan ID tiket
GRANT USAGE, SELECT ON SEQUENCE public.tickets_id_seq
TO authenticated;
